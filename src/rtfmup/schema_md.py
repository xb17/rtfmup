"""`docs/schema.md`: the analysis schema as Markdown, generated from the models (T4.4).

Built from `Analysis.model_json_schema()`, the same source as `schema/analysis.v1.json`,
so the two cannot drift apart: a test regenerates this file and compares.
"""

from __future__ import annotations

import json
from typing import Any

from rtfmup.models import Analysis

_HEAD = """\
# Analysis schema (v1)

Generated by `rtfmup schema --markdown` from the models in `src/rtfmup/models.py`. Do
not edit by hand: a test fails when this file differs from the generator's output. The
machine-readable form is `schema/analysis.v1.json` (`rtfmup schema`).

`rtfmup scan --json` prints one `Analysis`. Every model rejects unknown keys. Lists are
sorted deterministically, so two runs on the same tree give identical bytes.
"""


def _ref(name: str) -> str:
    return f"[`{name}`](#{name.lower()})"


def _type(spec: dict[str, Any]) -> str:
    if "$ref" in spec:
        return _ref(spec["$ref"].rsplit("/", 1)[-1])
    if "anyOf" in spec:
        parts = [_type(s) for s in spec["anyOf"] if s.get("type") != "null"]
        text = " or ".join(parts)
        return (
            f"{text} or null"
            if any(s.get("type") == "null" for s in spec["anyOf"])
            else text
        )
    if "enum" in spec:
        return " / ".join(f"`{json.dumps(v)}`" for v in spec["enum"])
    if "const" in spec:
        return f"`{json.dumps(spec['const'])}`"
    kind = spec.get("type", "any")
    if kind == "array":
        return f"list of {_type(spec.get('items', {}))}"
    if kind == "object":
        extra = spec.get("additionalProperties")
        if isinstance(extra, dict):
            return f"map of string to {_type(extra)}"
        return "object"
    return {"integer": "integer", "boolean": "boolean", "string": "string"}.get(
        kind, str(kind)
    )


def _model(name: str, spec: dict[str, Any]) -> list[str]:
    required = set(spec.get("required", []))
    lines = [f"## {name}", ""]
    if doc := spec.get("description"):
        lines += [" ".join(doc.split()), ""]
    lines += ["| Field | Type | Required | Default |", "| --- | --- | --- | --- |"]
    for field, fspec in spec.get("properties", {}).items():
        default = f"`{json.dumps(fspec['default'])}`" if "default" in fspec else ""
        req = "yes" if field in required else "no"
        lines.append(f"| `{field}` | {_type(fspec)} | {req} | {default} |")
    lines.append("")
    return lines


def render_markdown() -> str:
    schema = Analysis.model_json_schema()
    defs: dict[str, Any] = schema.get("$defs", {})
    lines = _HEAD.splitlines() + [""]
    lines += _model("Analysis", schema)
    for name in sorted(defs):
        lines += _model(name, defs[name])
    return "\n".join(lines).rstrip("\n") + "\n"
